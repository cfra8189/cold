#!/usr/bin/env node
/* ============================================================================
   Fixture sync — the single mechanism that keeps the backend's fixture copy
   from silently drifting away from the frontend's approved Phase 1 fixtures.

   Canonical source of truth: src/live/fixtures/*.json (the same files the
   frontend imports directly, verified against official filings in Phase 1).

   This script reads those files and writes a generated TypeScript module,
   supabase/functions/live-data/shared/fixtures.ts, that embeds the exact
   same values. The Edge Function is self-contained (it does not reach across
   the repo into src/ at import time — Deno's module graph for a deployed
   function should stay inside its own function directory), so the generated
   file is the deliberate, auditable "second copy" — not an accidental one.

   Run: npm run sync:fixtures
   Verified by: supabase/functions/live-data/tests/fixtureDrift.test.ts,
   which re-reads both sides and fails if they no longer match.
   ========================================================================== */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
const fixturesDir = path.join(repoRoot, "src", "live", "fixtures");
const outFile = path.join(repoRoot, "supabase", "functions", "live-data", "shared", "fixtures.ts");

function readJson(name) {
  return JSON.parse(readFileSync(path.join(fixturesDir, name), "utf8"));
}

const O_COMPANY = readJson("O.company.json");
const O_FACTS = readJson("O.facts.json");
const O_QUOTE = readJson("O.quote.json");
const BRKB_COMPANY = readJson("BRKB.company.json");
const BRKB_FACTS = readJson("BRKB.facts.json");
const BRKB_QUOTE = readJson("BRKB.quote.json");

const banner = `/* ============================================================================
   AUTO-GENERATED — DO NOT EDIT BY HAND.

   Generated by scripts/sync-live-fixtures.mjs from src/live/fixtures/*.json,
   the same Phase 1 fixture files the frontend imports directly. Regenerate
   with:

     npm run sync:fixtures

   supabase/functions/live-data/tests/fixtureDrift.test.ts fails if this file
   no longer matches the source JSON, so a forgotten regeneration is caught
   by the test suite rather than silently shipped.
   ========================================================================== */

`;

const body =
  `export const O_COMPANY = ${JSON.stringify(O_COMPANY, null, 2)} as const;\n\n` +
  `export const O_FACTS = ${JSON.stringify(O_FACTS, null, 2)} as const;\n\n` +
  `export const O_QUOTE = ${JSON.stringify(O_QUOTE, null, 2)} as const;\n\n` +
  `export const BRKB_COMPANY = ${JSON.stringify(BRKB_COMPANY, null, 2)} as const;\n\n` +
  `export const BRKB_FACTS = ${JSON.stringify(BRKB_FACTS, null, 2)} as const;\n\n` +
  `export const BRKB_QUOTE = ${JSON.stringify(BRKB_QUOTE, null, 2)} as const;\n`;

writeFileSync(outFile, banner + body, "utf8");
console.log("Wrote " + path.relative(repoRoot, outFile));
